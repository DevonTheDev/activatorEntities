test("world kills count safely and finish exactly once", function()
    local env=gmod.new(); local ply, enemies=env.start(); local world=env.entity("worldspawn"); world.Nick=false
    for _, enemy in ipairs(enemies) do env.fire("OnNPCKilled", enemy, world) end
    eq(env.totalEnemies, 0); eq(env.messageCount("roundFinished"), 1)
    env.fire("OnNPCKilled", enemies[5], world)
    env.fire("OnNPCKilled", env.entity("npc_zombie"), world)
    eq(env.messageCount("roundFinished"), 1); eq(env.totalEnemies, 0)
    eq(env.timers.activatorSpawner.stopped, false)
end)
