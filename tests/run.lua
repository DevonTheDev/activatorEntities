local gmod = dofile("tests/gmod.lua")
local passed, failed = 0, 0
local function eq(actual, expected, context)
    assert(actual == expected, (context or "values differ") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function test(name, callback)
    local ok, message=pcall(callback)
    if ok then passed=passed+1; print("PASS " .. name)
    else failed=failed+1; print("FAIL " .. name .. "\n  " .. tostring(message)) end
end

test("reject event starts without using an activator", function()
    local env=gmod.new(); local ply=env.ready()
    env.receive("SendNPCInformation", ply, "Raid")
    eq(#env.ents.FindByName("devonsSpawnedEntity"), 0)
    eq(#env.ents.FindByClass("activatorent"), 3)
end)
test("only the interacting player can start the event", function()
    local env=gmod.new(); local ply, ent=env.ready(); local stranger=env.entity("player")
    ent:AcceptInput("Use", ply, ply)
    env.receive("SendNPCInformation", stranger, "Raid")
    eq(env.totalEnemies, 0)
end)
test("valid interaction starts the configured event once", function()
    local env=gmod.new(); local ply, enemies=env.start()
    eq(#enemies, 5); eq(env.totalEnemies, 5); eq(#env.ents.FindByClass("activatorent"), 0)
    env.fire("OnNPCKilled", enemies[1], ply)
    env.receive("SendNPCInformation", ply, "Raid")
    eq(env.totalEnemies, 4, "a replay must not replace a killed enemy")
end)
for _, case in ipairs({"expired", "dead", "distant", "wrong event", "removed"}) do
    test("reject " .. case .. " interaction", function()
        local env=gmod.new(); local ply, ent=env.ready(); ent:AcceptInput("Use", ply, ply)
        local event="Raid"
        if case == "expired" then env.now=10000 elseif case == "dead" then ply.alive=false
        elseif case == "distant" then ply:SetPos(env.Vector(10000,0,0))
        elseif case == "wrong event" then event="Forged" elseif case == "removed" then ent:Remove() end
        env.receive("SendNPCInformation", ply, event)
        eq(env.totalEnemies, 0)
    end)
end
