for _, kind in ipairs({"Activator", "Enemy"}) do
    test("add " .. kind .. " spawn without duplicating an existing map", function()
        local env=gmod.new(); local admin=env.entity("player"); admin.admin=true
        table.insert(env.SpawnPositions, {map="other_map", enemySpawnPositions={}, activatorSpawnPositions={}})
        env.fire("PlayerSay", admin, "!set" .. kind .. "Spawn")
        eq(#env.SpawnPositions, 2); eq(#admin.chats, 1)
        eq(#env.SpawnPositions[1][kind == "Activator" and "activatorSpawnPositions" or "enemySpawnPositions"], 4)
    end)
    test("add " .. kind .. " spawn to an empty map config", function()
        local env=gmod.new(); local admin=env.entity("player"); admin.admin=true; env.SpawnPositions={}
        env.fire("PlayerSay", admin, "!set" .. kind .. "Spawn")
        eq(#env.SpawnPositions, 1); eq(#admin.chats, 1)
    end)
    test("remove the final " .. kind .. " spawn without errors or contradictory notices", function()
        local env=gmod.new(); local admin=env.entity("player"); admin.admin=true
        local key=kind == "Activator" and "activatorSpawnPositions" or "enemySpawnPositions"
        env.SpawnPositions[1][key]={env.Vector(0,0,0)}
        env.fire("PlayerSay", admin, "!remove" .. kind .. "Spawn")
        eq(#env.SpawnPositions[1][key], 0); eq(#admin.chats, 1)
        env.fire("PlayerSay", admin, "!remove" .. kind .. "Spawn"); eq(#admin.chats, 2)
    end)
end
