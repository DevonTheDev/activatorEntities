test("completion popup closes once after five seconds and leaves no repeating timer", function()
    local env=gmod.new(true); env.receive("roundFinished", nil)
    local frame=env.panels[1]; eq(frame.valid, true)
    eq(env.timers.destroyAlertFrame.delay, 5)
    eq(env.timers.destroyAlertFrame.repetitions, 1)
    env.fireTimer("destroyAlertFrame")
    eq(frame.valid, false); eq(env.panels[2].valid, false)
    eq(env.timers.destroyAlertFrame, nil)
end)
test("a new completion popup replaces the old frame and restarts its dismissal", function()
    local env=gmod.new(true); env.receive("roundFinished", nil)
    local first=env.panels[1]; local oldCallback=env.timers.destroyAlertFrame.callback
    env.receive("roundFinished", nil)
    local latest=env.panels[3]
    eq(first.valid, false); eq(env.panels[2].valid, false); eq(latest.valid, true)
    oldCallback() -- A stale callback must not remove the replacement.
    eq(latest.valid, true); assert(env.timers.destroyAlertFrame)
    env.fireTimer("destroyAlertFrame")
    eq(latest.valid, false); eq(env.timers.destroyAlertFrame, nil)
end)
